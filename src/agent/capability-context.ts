import type { ToolContext } from "../tools/contracts.js";

export function buildCapabilityContext(limits: ToolContext["limits"]): string {
  return [
    "利用できる操作: Minecraftの現在状態・周囲の観測、日本語チャットの送信、認可済み利用者への安全距離追従、停止、上限距離内の移動、保護条件に従う原木の収集と帰還、鉄を含む許可済み自然資源の採掘・ドロップ回収・必要な精錬、クラフト・限定した設置、小規模拠点の設営、Bot自身の所持防具の装着、構造化記憶の保存・検索、登録済み拠点と指定チェストへの原木収納です。",
    "敵対的なmobへの対処を明示的に頼まれたら、Bot自身の観測から安全な攻撃か実際の退避を選び、移動や死亡を再観測して報告します。プレイヤーや友好的なmobは攻撃しません。危険な条件で撃破を約束しません。",
    `移動距離の上限は${String(limits.maxMoveDistance)}ブロック、1回の安全な資源操作の数量上限は${String(limits.maxGatherCount)}個です。これは目標全体の達成可能数ではありません。大きな目的は段階に分けて進められますが、観測できる資源、所持品の空き、安全、継続作業の状態を確かめずに完遂を約束してはいけません。追従・帰還の安全距離は${String(limits.followDistance)}ブロックに設定済みです。距離未指定の帰還依頼ではこの値を使います。`,
    "提供していない操作: 一般的な建築、建築目的の任意ブロックの設置や破壊、サーバー管理、shell・ファイル操作、利用者の未観測の体調や状態の断定です。許可済み原木収集の対象原木だけは収集toolで扱います。",
    "提供していない操作を頼まれたら、できないことを短く明言し、実行済みと扱わず、目的に近い利用可能な操作があれば一つだけ提案してください。",
  ].join("\n");
}
